package org.apache.hertzbeat.manager.monitor.batch;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import org.junit.jupiter.api.Test;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.ArrayList;
import java.util.UUID;
import java.util.concurrent.Callable;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

class MonitorParamIdentityConcurrencyTest {
    @Test
    void concurrentMysqlModeIdentityWritesCommitAndRollbackWithoutFalseReceipts() throws Exception {
        var source = new DriverManagerDataSource(
                "jdbc:h2:mem:batch-identity-" + UUID.randomUUID() + ";MODE=MYSQL;LOCK_TIMEOUT=5000", "sa", "");
        var jdbc = new JdbcTemplate(source);
        var transaction = new TransactionTemplate(new DataSourceTransactionManager(source));
        // Synthetic native-shaped rows only; never opens an application database or schedules jobs.
        try (var anchor = source.getConnection(); var workers = Executors.newFixedThreadPool(10)) {
            jdbc.execute("CREATE TABLE hzb_monitor (id BIGINT PRIMARY KEY)");
            jdbc.execute("CREATE TABLE hzb_param (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "monitor_id BIGINT, field VARCHAR(30), param_value VARCHAR(100), "
                    + "CONSTRAINT target_field UNIQUE(monitor_id, field))");
            for (int round = 0; round < 4; round++) {
                var start = new CountDownLatch(1);
                var tasks = new ArrayList<Callable<Void>>();
                for (int item = 1; item <= 50; item++) {
                    long monitorId = round * 50L + item;
                    tasks.add(() -> {
                        start.await();
                        transaction.executeWithoutResult(status -> {
                            jdbc.update("INSERT INTO hzb_monitor(id) VALUES (?)", monitorId);
                            for (int field = 0; field < 5; field++) {
                                jdbc.update("INSERT INTO hzb_param(id,monitor_id,field,param_value) "
                                        + "VALUES(DEFAULT,?,?,?)", monitorId, "field" + field, "synthetic");
                            }
                        });
                        return null;
                    });
                }
                var submitted = tasks.stream().map(workers::submit).toList();
                start.countDown();
                for (var result : submitted) {
                    result.get(20, TimeUnit.SECONDS);
                }
            }
            assertEquals(200, jdbc.queryForObject("SELECT COUNT(*) FROM hzb_monitor", Integer.class));
            assertEquals(1000, jdbc.queryForObject("SELECT COUNT(DISTINCT id) FROM hzb_param", Integer.class));
            assertThrows(DuplicateKeyException.class, () -> transaction.executeWithoutResult(status -> {
                jdbc.update("INSERT INTO hzb_monitor(id) VALUES (999)");
                jdbc.update("INSERT INTO hzb_param(id,monitor_id,field) VALUES(DEFAULT,999,'duplicate')");
                jdbc.update("INSERT INTO hzb_param(id,monitor_id,field) VALUES(DEFAULT,999,'duplicate')");
            }));
            assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM hzb_monitor WHERE id=999", Integer.class));
            assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM hzb_param WHERE monitor_id=999", Integer.class));
        }
    }
}
