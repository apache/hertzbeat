package org.apache.hertzbeat.common.util;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNotSame;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.lang.reflect.Field;
import java.util.HashMap;
import java.util.Map;

import org.apache.commons.jexl3.JexlEngine;
import org.apache.commons.jexl3.JexlExpression;
import org.apache.commons.jexl3.internal.Script;
import org.junit.jupiter.api.Test;

/**
 * Test case for {@link JexlExpressionRunner}
 */
public class JexlExpressionRunnerTest {
    @Test
    void evaluate() {
        Map<String, Object> context = new HashMap<String, Object>();
        context.put("age", 2);
        context.put("__age__", 2);

        String expression = "1 + 2";
        String expressionWithParam = "1 + age";
        String expressionWithName = "1 + __age__";

        assertEquals(3, JexlExpressionRunner.evaluate(expression));
        assertEquals(3, JexlExpressionRunner.evaluate(expression, context));
        assertEquals(3, JexlExpressionRunner.evaluate(expressionWithParam, context));
        assertEquals(3, JexlExpressionRunner.evaluate(expressionWithName, context));

        assertThrows(NullPointerException.class, () -> {
            JexlExpressionRunner.evaluate(expression, null);
        });

        JexlExpression expObj = JexlExpressionRunner.compile(expression);
        assertNotNull(expObj);
        assertEquals(3, JexlExpressionRunner.evaluate(expObj, context));
    }

    @Test
    void commonFuncs() {
        assertEquals(true, JexlExpressionRunner.evaluate("equals(1, 1)"));
        assertEquals(true, JexlExpressionRunner.evaluate("equals(null, null)"));
        assertEquals(false, JexlExpressionRunner.evaluate("equals(null, 1)")); 
        assertEquals(true, JexlExpressionRunner.evaluate("""
                contains("abc", "a")
                """)); 
        assertEquals(true, JexlExpressionRunner.evaluate("""
                contains("Abc", "a")
                """)); 
    }

    @Test
    void testJsonFunction() {
        Map<String, Object> context = new HashMap<String, Object>();
        context.put("$.info", "{\"current\":537132,\"grantTotal\":63129,\"instanceCode\":\"CSDZMC\",\"timeMillis\":1754579874357}");

        String expression = "json:apply($.info).current";

        JexlExpression expObj = JexlExpressionRunner.compile(expression);
        assertEquals(537132, JexlExpressionRunner.evaluate(expObj, context));

        context.put("$.info", "{\"grantTotal\":63129,\"instanceCode\":\"CSDZMC\",\"timeMillis\":1754579874357}");
        assertNull(JexlExpressionRunner.evaluate(expObj, context));

        context.clear();
        assertNull(JexlExpressionRunner.evaluate(expObj, context));
    }

    @Test
    void longAlertRuleShouldHitParseCache() {
        // a typical alert rule generated by the web ui, longer than the jexl default cache threshold (64)
        String rule = "equals(__app__,\"linux\") && equals(__metrics__,\"cpu\") "
                + "&& equals(__instance__, \"7\") && usage > 90";
        assertTrue(rule.length() > 64);

        JexlExpression first = JexlExpressionRunner.compile(rule);
        JexlExpression second = JexlExpressionRunner.compile(rule);
        assertSame(parsedTree(first), parsedTree(second));

        Map<String, Object> context = new HashMap<>();
        context.put("__app__", "linux");
        context.put("__metrics__", "cpu");
        context.put("__instance__", "7");
        context.put("usage", 95);
        assertEquals(true, JexlExpressionRunner.evaluate(second, context));
        context.put("usage", 80);
        assertEquals(false, JexlExpressionRunner.evaluate(second, context));
    }

    @Test
    void cacheThresholdBoundary() {
        String belowThreshold = expressionOfLength(JexlExpressionRunner.CACHE_THRESHOLD - 1);
        assertSame(parsedTree(JexlExpressionRunner.compile(belowThreshold)),
                parsedTree(JexlExpressionRunner.compile(belowThreshold)));
        assertEquals(true, JexlExpressionRunner.evaluate(belowThreshold));

        String atThreshold = expressionOfLength(JexlExpressionRunner.CACHE_THRESHOLD);
        assertNotSame(parsedTree(JexlExpressionRunner.compile(atThreshold)),
                parsedTree(JexlExpressionRunner.compile(atThreshold)));
        assertEquals(true, JexlExpressionRunner.evaluate(atThreshold));
    }

    @Test
    void defaultCacheThresholdWouldNotCacheLongExpression() {
        // documents the behavior before the threshold was raised: expressions of 64+ chars were re-parsed every time
        JexlEngine defaultThresholdEngine = JexlExpressionRunner.buildEngine(64);
        String expression = expressionOfLength(64);
        assertNotSame(parsedTree(defaultThresholdEngine.createExpression(expression)),
                parsedTree(defaultThresholdEngine.createExpression(expression)));
    }

    /**
     * build a valid boolean expression with exactly the given length, eg: 'aaaa' != ''
     */
    static String expressionOfLength(int length) {
        String expression = "'" + "a".repeat(length - 8) + "' != ''";
        assertEquals(length, expression.length());
        return expression;
    }

    /**
     * the parsed AST held by the expression, the same instance means it was served from the parse cache
     */
    static Object parsedTree(JexlExpression expression) {
        try {
            Field field = Script.class.getDeclaredField("script");
            field.setAccessible(true);
            return field.get(expression);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
    }
}
