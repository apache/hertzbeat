package org.apache.hertzbeat.common.util;

import com.google.common.collect.Maps;
import org.apache.commons.jexl3.JexlBuilder;
import org.apache.commons.jexl3.JexlContext;
import org.apache.commons.jexl3.JexlEngine;
import org.apache.commons.jexl3.JexlExpression;
import org.apache.commons.jexl3.JexlFeatures;
import org.apache.commons.jexl3.MapContext;
import org.apache.hertzbeat.common.constants.CommonConstants;

import java.nio.charset.StandardCharsets;
import java.util.Map;
import java.util.function.Function;
import tools.jackson.core.type.TypeReference;

/**
 * jexl express runner
 */
public class JexlExpressionRunner {

    private static final String LOADER_NAME = "jexl-class-loader";

    /**
     * max number of parsed expressions kept in the jexl engine cache
     */
    static final int CACHE_SIZE = 256;

    /**
     * expressions whose length is less than this threshold are cached after parsing.
     * jexl defaults to 64, which excludes most alert rules generated by the web ui (typically 70~300 chars),
     * so they would be re-parsed on every evaluation. 1024 covers 99.4% of the expressions in the built-in
     * monitoring templates, only the longest idrac enum-mapping calculate (1715 chars, compiled once per cycle) is left out.
     */
    static final int CACHE_THRESHOLD = 1024;

    private static final JexlEngine jexlEngine = buildEngine(CACHE_THRESHOLD);

    /**
     * build a jexl engine with the hertzbeat sandbox features and functions
     *
     * @param cacheThreshold max expression length (exclusive) eligible for the parse cache
     * @return jexl engine
     */
    static JexlEngine buildEngine(int cacheThreshold) {
        Map<String, Object> functions = Maps.newLinkedHashMap();
        // set the root namespace function
        functions.put(null, new JexlCommonFunction());
        functions.put(CommonConstants.JEXL_CUSTOM_JSON_FUNCTION, jsonFunction());
        ClassLoader classLoader = new ClassLoader() {
            @Override
            public String getName() {
                return LOADER_NAME;
            }
        };
        JexlFeatures features = new JexlFeatures();
        features.annotation(false).loops(false).pragma(false)
                .methodCall(false).lambda(false).newInstance(false).register(false);
        return new JexlBuilder().charset(StandardCharsets.UTF_8).cache(CACHE_SIZE).cacheThreshold(cacheThreshold)
                .loader(classLoader).features(features).strict(true).silent(false).stackOverflow(40)
                .namespaces(functions).create();
    }

    public static Object evaluate(String expression, Map<String, Object> context) {
        JexlContext jexlContext = new MapContext();
        for (Map.Entry<String, Object> entry : context.entrySet()) {
            jexlContext.set(entry.getKey(), entry.getValue());
        }
        return jexlEngine.createExpression(expression).evaluate(jexlContext);
    }

    public static Object evaluate(JexlExpression expression, Map<String, Object> context) {
        JexlContext jexlContext = new MapContext();
        for (Map.Entry<String, Object> entry : context.entrySet()) {
            jexlContext.set(entry.getKey(), entry.getValue());
        }
        return expression.evaluate(jexlContext);
    }

    public static Object evaluate(String expression) {
        return jexlEngine.createExpression(expression).evaluate(new MapContext());
    }

    public static JexlExpression compile(String expression) {
        return jexlEngine.createExpression(expression);
    }

    /**
     * custom function `json:apply(xx)`
     *
     * @return java.util.function.Function
     */
    private static Function<String, Map<String, Object>> jsonFunction() {
        return json -> {
            TypeReference<Map<String, Object>> typeReference = new TypeReference<>() {
            };
            return JsonUtil.fromJson(json, typeReference);
        };
    }
}
